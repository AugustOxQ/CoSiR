"""Round 6 describe-then-score value listing (DECISION_RULE.md of this folder: section 7 item 2, section 8 item 3;
contracts section 9; settings in dts_settings.json): Qwen3-VL-8B-Instruct, text only, greedy, at most 128 new tokens,
asked "List K distinct values of the following criterion for describing paintings: <phrase>. One value per line, no
numbering." with K written as a number. Batches of 16 prompts, left padding, in the input's order (agent default).

Input. <job>/listing_input.jsonl, one line {"phrase": <normalised phrase>, "K": 8 | 16} per distinct pair (written by
the CPU side; DTS-N's phrases are the aspect names, the only place a GPU job sees them).

Output. <out>/listings.jsonl, one line {"phrase", "K", "answer"} (the raw answer) per input pair, and provenance.json.
The file is rewritten atomically after the batch that completes 50 new calls; a rerun into the same folder resumes.

Cache. One listing per (phrase, K) across runs: the listings of earlier runs are copied, not recomputed. A cache is an
earlier output folder (listings.jsonl and provenance.json) whose fingerprint (model, snapshot, settings SHA-256, the
two scripts' SHA-256) equals this run's; every folder under <job>/cache/ and every --cache folder is one. No metric is
computed or printed.

Run (DAS6 through scripts/run_r6_listing.sh; the local GPU only under its lock):
    python r6_gpu_listing.py --job-dir <job folder> --out <output folder> [--cache <folder>]... [--check-only [--no-model]]
"""
import argparse
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import r6_gpu_common as G  # noqa: E402

FIELDS = ("phrase", "K", "answer")
KEY_FIELDS = ("phrase", "K")
INPUT_NAME = "listing_input.jsonl"


def listing_prompt(phrase, K, settings) -> str:
    return settings["listing"]["prompt"].format(K=int(K), phrase=phrase)


def listing_messages(phrase, K, settings) -> list:
    return [{"role": "user", "content": [{"type": "text", "text": listing_prompt(phrase, K, settings)}]}]


def load_listing_input(path, settings) -> list:
    """[(phrase, K)] in file order; every phrase a non-empty single normalised line, K one of the rule's, no repeats."""
    path = Path(path)
    items, seen = [], set()
    text = path.read_text(encoding="utf-8")
    G._require(text.endswith("\n"), f"{path}: the last line is incomplete")
    for i, line in enumerate(text.split("\n")[:-1]):          # split on newline only, as KeyedJsonl
        rec = json.loads(line)
        G._require(isinstance(rec, dict) and sorted(rec) == ["K", "phrase"], f"{path}:{i + 1}: keys must be phrase, K")
        p, K = rec["phrase"], rec["K"]
        G._require(isinstance(p, str) and p and p == p.strip() and p == p.lower() and len(p.splitlines()) == 1,
                   f"{path}:{i + 1}: phrase {p!r} is not a non-empty normalised line")
        G._require(type(K) is int and K in settings["listing"]["K"], f"{path}:{i + 1}: K {K!r} is not 8 or 16")
        G._require((p, K) not in seen, f"{path}:{i + 1}: repeated ({p!r}, {K})")  # guard:input_unique
        seen.add((p, K))
        items.append((p, K))
    G._require(items, f"{path}: no listing requested")
    return items


def load_caches(dirs, fingerprint) -> dict:
    """{(phrase, K): answer} from earlier output folders of the same fingerprint."""
    out = {}
    for d in dirs:
        d = Path(d)
        prov = json.loads((d / "provenance.json").read_text())
        G._require(prov.get("fingerprint") == fingerprint,
                   f"{d}: a cache made by another model, settings or script cannot be reused")  # guard:cache_fingerprint
        st = G.KeyedJsonl(d / "listings.jsonl", FIELDS, KEY_FIELDS)
        st.load()
        for rec in st.records():
            k = (rec["phrase"], rec["K"])
            G._require(out.get(k, rec["answer"]) == rec["answer"], f"caches disagree on {k}")
            out[k] = rec["answer"]
    return out


def run_listing(items, settings, out_dir, generate_batch, cache, batch_size, every=G.CHECKPOINT_EVERY,
                max_calls=None, log=print) -> dict:
    """Fill <out_dir>/listings.jsonl with one record per (phrase, K) of ``items``: already written ones are kept,
    cached ones copied, the rest generated by ``generate_batch(list of messages) -> list of str`` in input order."""
    allowed = set(items)
    store = G.KeyedJsonl(Path(out_dir) / "listings.jsonl", FIELDS, KEY_FIELDS)
    n_before = store.load(allowed)
    n_cached = 0
    for p, K in items:
        if (p, K) not in store and (p, K) in cache:
            store.add({"phrase": p, "K": K, "answer": cache[(p, K)]}, allowed)
            n_cached += 1
    todo = [k for k in items if k not in store]
    log(f"listing: {len(items)} planned, {n_before} already written, {n_cached} from cache, {len(todo)} to run")
    n, since, t0 = 0, n_cached, time.time()
    for i in range(0, len(todo), batch_size):
        batch = todo[i:i + batch_size]
        answers = generate_batch([listing_messages(p, K, settings) for p, K in batch])
        G._require(len(answers) == len(batch) and all(isinstance(a, str) for a in answers),
                   "the model returned something other than one text per prompt")
        for (p, K), a in zip(batch, answers):
            store.add({"phrase": p, "K": K, "answer": a}, allowed)
        n, since = n + len(batch), since + len(batch)
        if since >= every:
            store.save()  # guard:listing_checkpoint
            since = 0
            log(f"listing: {n}/{len(todo)} generated, {(time.time() - t0) / n:.2f} s per prompt")
        if max_calls is not None and n >= max_calls:
            break
    store.save()
    return {"n_planned": len(items), "n_done_before": n_before, "n_cached": n_cached, "n_called": n,
            "complete": len(store) == len(items), "s_per_prompt": (time.time() - t0) / n if n else None}


def make_generate_batch(processor, model, settings):
    tok = processor.tokenizer
    tok.padding_side = settings["generation"]["listing"]["padding_side"]
    max_new = settings["generation"]["listing"]["max_new_tokens"]

    def render(conv):
        text = processor.apply_chat_template(conv, tokenize=False, add_generation_prompt=True)
        if isinstance(text, list):
            G._require(len(text) == 1, "one conversation rendered to several prompts")
            text = text[0]
        return text

    def generate_batch(conversations):
        enc = tok([render(c) for c in conversations], return_tensors="pt", padding=True,
                  add_special_tokens=False).to(model.device)
        return G.generate_texts(model, processor, enc, max_new, settings)
    return generate_batch


def parse_args(argv=None):
    ap = argparse.ArgumentParser(description="Round 6 DTS value listing (rule section 7 item 2); prints no metric")
    ap.add_argument("--job-dir", required=True, help=f"folder with {INPUT_NAME} (and optional cache/<run>/ folders)")
    ap.add_argument("--out", required=True, help="output folder (listings.jsonl, provenance.json)")
    ap.add_argument("--cache", action="append", default=[], help="an earlier output folder to reuse (repeatable)")
    ap.add_argument("--check-only", action="store_true",
                    help="check input, caches and snapshot, then list the first prompts batched and one by one")
    ap.add_argument("--no-model", action="store_true", help="with --check-only: stop before loading the model")
    ap.add_argument("--hub-cache", default=None, help="HF hub cache (default $HF_HUB_CACHE)")
    args = ap.parse_args(argv)
    if args.no_model and not args.check_only:
        ap.error("--no-model needs --check-only")
    return args


def main(argv=None) -> int:
    args = parse_args(argv)
    settings, settings_sha = G.load_settings()
    job = Path(args.job_dir)
    items = load_listing_input(job / INPUT_NAME, settings)
    snap = G.snapshot_dir(G.hub_cache(args.hub_cache), settings["model"]["id"], settings["model"]["snapshot"])
    snap_info = G.check_snapshot(snap)
    fingerprint = {"job": "r6_gpu_listing", "model_id": settings["model"]["id"],
                   "snapshot": settings["model"]["snapshot"], "settings_sha256": settings_sha,
                   "scripts_sha256": G.script_shas(__file__, G.__file__)}
    cache_dirs = sorted(p for p in (job / "cache").glob("*") if p.is_dir()) + [Path(c) for c in args.cache]
    cache = load_caches(cache_dirs, fingerprint)
    batch_size = int(settings["generation"]["listing"]["batch_size"])
    print(f"listing inputs ok: {len(items)} (phrase, K) pairs, {sum(k in cache for k in items)} cached in "
          f"{len(cache_dirs)} folders, batch size {batch_size}, snapshot {snap_info['files']} files, "
          f"settings {settings_sha[:12]}", flush=True)
    run = {"args": vars(args), "input_sha256": G.sha256_file(job / INPUT_NAME), "n_input": len(items),
           "caches": {str(d): G.sha256_file(Path(d) / "listings.jsonl") for d in cache_dirs}, "snapshot": snap_info}
    if args.check_only:
        sample = items[:min(4, len(items))]
        for p, K in sample:
            listing_messages(p, K, settings)
        v = G.check_imports()
        print(f"imports ok: torch {v['torch']}, transformers {v['transformers']}", flush=True)
        if args.no_model:
            print("check-only --no-model: prompts built; stopping before the model", flush=True)
            return 0
        out = Path(args.out) / f"check_only_{G.amsterdam_now().replace(' ', '_').replace(':', '')}"
        prov = G.begin_provenance(out, fingerprint, dict(run, check_only=True))
        t0 = time.time()
        processor, model = G.load_model(snap, settings)
        load_s = time.time() - t0
        gen = make_generate_batch(processor, model, settings)
        res = run_listing(sample, settings, out, gen, {}, batch_size, every=1)
        st = G.KeyedJsonl(out / "listings.jsonl", FIELDS, KEY_FIELDS)
        st.load()
        batched = {(r["phrase"], r["K"]): r["answer"] for r in st.records()}
        same = sum(gen([listing_messages(p, K, settings)])[0] == batched[(p, K)] for p, K in sample)
        import torch
        G.end_provenance(out, prov, status="check-only", model_load_s=load_s, versions=G.versions(),
                         batch_vs_single_identical=f"{same} of {len(sample)}",
                         peak_gpu_mem_bytes=int(torch.cuda.max_memory_allocated()), **res)
        print(f"check-only: model loaded in {load_s:.0f} s, {res['n_called']} prompts in one batch; batched and "
              f"one-by-one answers identical for {same} of {len(sample)}; outputs in {out}", flush=True)
        return 0
    out = Path(args.out)
    prov = G.begin_provenance(out, fingerprint, run)
    processor = model = None
    load_s = 0.0
    if any(k not in cache for k in items):
        t0 = time.time()
        processor, model = G.load_model(snap, settings)
        load_s = time.time() - t0
        G.update_provenance(out, prov, model_load_s=load_s, versions=G.versions())
    gen = make_generate_batch(processor, model, settings) if model is not None else None
    res = run_listing(items, settings, out, gen, cache, batch_size)
    extra = {}
    if model is not None:
        import torch
        extra["peak_gpu_mem_bytes"] = int(torch.cuda.max_memory_allocated())
    G.end_provenance(out, prov, status="complete" if res["complete"] else "partial", model_load_s=load_s, **extra,
                     **res)
    print(f"listing: {'complete' if res['complete'] else 'partial'}, outputs in {out}", flush=True)
    return 0 if res["complete"] else 1


if __name__ == "__main__":
    sys.exit(main())
